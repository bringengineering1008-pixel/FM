def render(post: dict, spec: dict) -> str:
    parts = [f"# {spec['title']}", "", *spec["hook"], "", "![대표 이미지](thumbnail.jpg)", ""]
    heading_at = {0: spec["headings"][0], 4: spec["headings"][1], 7: spec["headings"][2]}
    for index, note in enumerate(spec["notes"]):
        if index in heading_at:
            parts.extend([f"## {heading_at[index]}", ""])
        parts.extend(
            [
                f"![장면 {index + 1:02d}](scene-{index + 1:02d}.jpg)",
                "",
                f"<b>그림 설명</b> {note}",
                "",
                "브링이슈 해설: " + ROLE_COMMENTS[index].format(focus=spec["focus"]),
                "",
            ]
        )
    parts.extend(
        [
            f"<u>한 줄 정리: {spec['focus']}</u>",
            "",
            "<b>에디터의 시선</b>",
            "",
            spec["editor"],
            "",
            f"<u>{spec['question']}</u>",
            "",
            "---",
            "",
            f"원본 채널: {post['channel']}",
            f"원본 영상 제목: {post['source_title']}",
            f"원본 링크: {post['url']}",
            "",
            "이 글은 원본 영상을 대체하지 않는 리뷰·해설 콘텐츠입니다. 장면 저작권은 원저작자와 해당 채널에 있으며, 영상의 맥락을 확인하려면 원본을 함께 봐주세요.",
            "",
            " ".join(f"#{tag}" for tag in spec["tags"]),
            "",
        ]
    )
    return "\n".join(parts)


def main() -> None:
    posts = json.loads(REGISTRY.read_text(encoding="utf-8"))["posts"]
    for post in posts:
        folder = ROOT / "blog-assets" / f"2026-08-22-{post['slug']}"
        draft = render(post, SPECS[post["slug"]])
        (folder / "post-draft.md").write_text(draft, encoding="utf-8")
        compact_length = len("".join(draft.split()))
        print(post["slug"], len(SPECS[post["slug"]]["title"]), compact_length)


if __name__ == "__main__":
    main()
