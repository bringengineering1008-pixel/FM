def render_draft(post: dict) -> str:
    points = BODY_COPY[post["slug"]]
    display_source_title = post["source_title"]
    if len(display_source_title) > 60:
        display_source_title = display_source_title[:57].rstrip() + "…"
    scene_captions = [
        "이야기의 첫인상",
        "상황이 시작된 지점",
        "첫 번째 변화",
        "놓치면 안 될 맥락",
        "선택이 드러난 순간",
        "분위기가 바뀐 장면",
        "가장 중요한 단서",
        "결과가 보인 순간",
        "마지막에 남은 여운",
    ]
    lines = [
        f"# {post['draft_title']}",
        "",
        "![대표 이미지](thumbnail.jpg)",
        "",
        "처음에는 제목이 조금 과장된 줄 알았습니다.",
        "",
        "그런데 영상을 끝까지 보니 시선을 붙잡은 건",
        "화제성보다 그 안에 숨은 선택의 과정이었습니다.",
        "",
        f"<b>{display_source_title}</b>",
        "",
        f"<u>{post['editorial_angle']}</u>",
        "",
        "오늘은 장면을 차례로 보면서",
        "왜 이 영상이 지금 반응을 얻는지 정리해보겠습니다. 👀",
        "",
        "> 첫인상보다 중요한 건 장면 사이에서 바뀌는 판단이었습니다.",
        "",
    ]
    for index, (caption, point) in enumerate(zip(scene_captions, points), start=1):
        lines.extend(
            [
                f"![장면 {index:02d}](scene-{index:02d}.jpg)",
                "",
                f"*{caption}*",
                "",
                (f"<b>{point}</b>" if index in (4, 7) else point),
                "",
            ]
        )
        if index == 5:
            lines.extend(
                [
                    "> 여기서부터 영상의 제목이 단순한 자극이 아니었다는 게 보입니다.",
                    "",
                ]
            )
    lines.extend(
        [
            "화면만 빠르게 넘기면 놓치기 쉽지만",
            "이 영상은 결국 한 번의 결과보다 선택이 쌓이는 과정을 보여줍니다.",
            "",
            "<b>그래서 보고 난 뒤에는 처음과 다른 질문이 남습니다.</b>",
            "",
            "여러분은 어느 장면에서 생각이 가장 많이 바뀌셨나요? 🙂",
            "",
            f"원본 영상: {post['url']}",
            f"출처: YouTube · {post['channel']}",
            "",
            "※ 본문 이미지는 원본 영상을 설명·비평하기 위한 장면 인용입니다.",
            "※ 영상 전체를 대신하지 않으며 권리는 원저작자에게 있습니다.",
            "",
            f"#브링이슈 #{post['topic'].replace('·', '')} #오늘뜬유튜브 #유튜브리뷰",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    for post in load_registry()["posts"]:
        output = asset_dir(post) / "post-draft.md"
        output.write_text(render_draft(post), encoding="utf-8")
        print(output)


if __name__ == "__main__":
    main()
